/**
 * The two payloads of a browser interview: a round the agent writes, and the
 * answers the person gives it.
 *
 * An interview is file-based and round-based, so it works the same under
 * every harness: nothing in the browser talks to the agent. The agent writes
 * `rounds/round-NN.json`, blocks on `vinta-ai-maestro interview wait`, and
 * resumes when `answers/round-NN.json` lands. The browser side is the
 * interview page the interview server serves (`server.ts`); the agent side is
 * whatever skill is running the interview — `create-spec`'s Step 0 today.
 *
 * These schemas are the source of truth for `schemas/interview-round.v1` and
 * `schemas/interview-answers.v1` at the repo root, generated by `generate.ts`
 * and byte-compared in `tests/interview.test.ts`. Every description here
 * reaches the agent through the JSON Schema, so they are written for the
 * agent authoring a round, not for a reader of this file.
 */
import { z } from 'zod'

export const INTERVIEW_ROUND_SCHEMA_URL =
  'https://github.com/vintasoftware/vinta-ai-workflows/schemas/interview-round.v1.schema.json'
export const INTERVIEW_ANSWERS_SCHEMA_URL =
  'https://github.com/vintasoftware/vinta-ai-workflows/schemas/interview-answers.v1.schema.json'

/** Where an explainer document may live: under the interview's `docs/`, as Markdown or HTML. */
export const DOC_PATH_PATTERN = /^(docs\/)?[^\0]+\.(md|markdown|html|htm)$/

const DocPathSchema = z
  .string()
  .regex(DOC_PATH_PATTERN)
  .describe(
    'Relative to the interview dir, inside `docs/` (e.g. `docs/D4-concurrency.md`). The server refuses anything that escapes `docs/`.',
  )

/**
 * Rich explanation. Either inline Markdown (a string, or `{markdown}`) or a
 * file under `<interview-dir>/docs/` (`{path}`).
 */
export const ExplainerSchema = z
  .union([
    z.string().min(1).describe('Inline Markdown. Mermaid fences allowed.'),
    z
      .strictObject({
        title: z.string().optional(),
        markdown: z.string().min(1).describe('Inline Markdown. Mermaid fences allowed.'),
      })
      .describe('Inline Markdown with a title.'),
    z
      .strictObject({
        title: z.string().optional(),
        path: DocPathSchema,
      })
      .describe(
        'A document under `docs/`. `.md` files render in the page with Mermaid support; `.html` files render in a sandboxed iframe, for layouts Markdown cannot express.',
      ),
  ])
  .meta({ id: 'explainer' })
  .describe(
    'Rich explanation. Either inline Markdown (string or `{markdown}`) or a file under `<interview-dir>/docs/` (`{path}`). `.md` files render in the page with Mermaid support; `.html` files render in a sandboxed iframe for layouts Markdown cannot express.',
  )

export const TAG_TONES = ['neutral', 'warn', 'ok'] as const
export type TagTone = (typeof TAG_TONES)[number]

export const TagSchema = z
  .union([
    z.string(),
    z.strictObject({
      label: z.string(),
      tone: z.enum(TAG_TONES).optional(),
    }),
  ])
  .meta({ id: 'tag' })

export const OptionSchema = z.strictObject({
  value: z.string().min(1).describe('Stable machine value echoed back in `answers[].values`.'),
  label: z.string().min(1).describe('Short card title, a few words.'),
  description: z.string().optional().describe('One or two sentences: what this option is.'),
  consequences: z
    .string()
    .optional()
    .describe(
      'What picking this implies downstream — a new plan phase, a one-way door, a dependency, a cost. The "choose wisely" line.',
    ),
  recommended: z
    .boolean()
    .optional()
    .describe("Marks the agent's recommended default. At most one per decision."),
  tags: z
    .array(TagSchema)
    .optional()
    .describe('Small pills under the card, e.g. `{label: "One-way door", tone: "warn"}`.'),
  explainer: ExplainerSchema.optional(),
}).meta({ id: 'option' })

export const INPUT_TYPES = ['single', 'multi', 'text', 'confirm'] as const
export type InputType = (typeof INPUT_TYPES)[number]

export const InputSchema = z.strictObject({
  type: z
    .enum(INPUT_TYPES)
    .describe(
      '`single` — pick one option; `multi` — pick any; `text` — free-form answer; `confirm` — like `single`, for yes/no and read-back confirmations.',
    ),
  options: z.array(OptionSchema).optional(),
  allow_other: z
    .boolean()
    .optional()
    .describe(
      'Adds a "Something else" card with a text field. Default: on when `options` is empty, off otherwise.',
    ),
  other_label: z.string().optional(),
  other_placeholder: z.string().optional(),
  label: z.string().optional().describe('`text` input only — field label.'),
  placeholder: z
    .string()
    .optional()
    .describe('`text` input only — placeholder with a real example answer.'),
}).meta({ id: 'input' })

export const DecisionSchema = z.strictObject({
  id: z
    .string()
    .min(1)
    .describe(
      'Stable id within the interview (e.g. `D4`). Reused across rounds when a decision is re-asked.',
    ),
  title: z.string().min(1).describe('The question, as a full sentence the user can answer.'),
  short: z.string().optional().describe('Rail label when `title` is long.'),
  why: z
    .string()
    .optional()
    .describe(
      'One sentence on why the answer matters (the `*Why:*` line from the create-spec question bank).',
    ),
  context: z
    .string()
    .optional()
    .describe(
      'Markdown: what the agent already knows that bears on this decision — earlier answers quoted back, repo facts, constraints. Mermaid fences allowed.',
    ),
  explainer: ExplainerSchema.optional(),
  required: z
    .boolean()
    .default(true)
    .describe('When `false`, the round can be submitted with this decision left open. Default `true`.'),
  waivable: z
    .boolean()
    .default(true)
    .describe('Show the "not applicable — skip" toggle. Default `true`.'),
  waive_label: z.string().optional(),
  input: InputSchema,
}).meta({ id: 'decision' })

export const GroupSchema = z.strictObject({
  id: z.string().min(1),
  title: z.string().min(1),
  decisions: z.array(DecisionSchema),
}).meta({ id: 'group' })

export const ReplySchema = z.strictObject({
  question_id: z
    .string()
    .optional()
    .describe('`questions[].id` from the answers payload being replied to.'),
  decision_id: z
    .string()
    .optional()
    .describe('Decision the question was about. Omit for general questions.'),
  question: z.string().describe("The user's question, quoted."),
  answer: z.string().describe('Markdown answer. Mermaid fences allowed.'),
}).meta({ id: 'reply' })

export const ROUND_KINDS = ['questions', 'readback'] as const
export type RoundKind = (typeof ROUND_KINDS)[number]

/** `interview.slug`: the interview's directory name, and what the page keys drafts on. */
export const SLUG_PATTERN = /^[a-z0-9][a-z0-9-]*$/

export const InterviewRoundSchema = z
  .strictObject({
    schema_version: z.literal(1),
    round: z
      .int()
      .min(1)
      .describe('1-based round number. Must match the `NN` in the filename (`round-01.json` → 1).'),
    interview: z.strictObject({
      slug: z
        .string()
        .regex(SLUG_PATTERN)
        .describe(
          'Stable kebab-case id for the whole interview. The page keys browser drafts on it; the agent uses it as the interview directory name.',
        ),
      title: z
        .string()
        .min(1)
        .describe('Human title shown in the header, e.g. `Order tags — spec interview`.'),
      skill: z
        .string()
        .optional()
        .describe('Skill that is running the interview (`create-spec`, `plan-feature`, …). Display only.'),
    }),
    kind: z
      .enum(ROUND_KINDS)
      .default('questions')
      .describe(
        '`questions` (default) renders decisions one per screen. `readback` additionally renders `summary` first — use it for the final "anything I got wrong before I draft?" round.',
      ),
    intro: z
      .string()
      .optional()
      .describe(
        'Markdown shown above the first decision — what this round is about, what changed since the last one.',
      ),
    summary: z
      .string()
      .optional()
      .describe(
        'Markdown read-back of every load-bearing decision so far. Rendered only when `kind` is `readback`.',
      ),
    replies: z
      .array(ReplySchema)
      .optional()
      .describe(
        'Agent answers to questions the user asked in earlier rounds (`interview-answers.v1` → `questions[]`). Shown next to the decision they refer to, or in the general panel when `decision_id` is absent.',
      ),
    groups: z
      .array(GroupSchema)
      .min(1)
      .describe('Ordered groups (the left rail). For `create-spec` these are its interview groups A–I.'),
  })
  .describe(
    'One round of an agent-driven interview, written by the agent to `<interview-dir>/rounds/round-NN.json` and rendered by the `vinta-ai-maestro` interview page as a full-screen decision form. Decisions are grouped; each decision carries the context the agent already knows, an optional explainer document (Markdown with Mermaid, or HTML), and options with their consequences. The browser answers with an `interview-answers.v1` payload.',
  )

export type InterviewRound = z.infer<typeof InterviewRoundSchema>
export type Decision = z.infer<typeof DecisionSchema>
export type DecisionInput = z.infer<typeof InputSchema>
export type Option = z.infer<typeof OptionSchema>
export type Explainer = z.infer<typeof ExplainerSchema>
export type Group = z.infer<typeof GroupSchema>
export type Reply = z.infer<typeof ReplySchema>

export const ANSWER_STATUSES = ['answered', 'waived', 'skipped'] as const
export type AnswerStatus = (typeof ANSWER_STATUSES)[number]

export const AnswerSchema = z.strictObject({
  decision_id: z.string().min(1),
  status: z
    .enum(ANSWER_STATUSES)
    .describe(
      '`answered` — a value is present; `waived` — user marked it not applicable (treat as explicitly out of scope, not as unknown); `skipped` — left open (only possible for `required: false` decisions). A `skipped` required-looking decision is **Open questions** material.',
    ),
  values: z
    .array(z.string())
    .optional()
    .describe(
      'Chosen option `value`s. One for `single` / `confirm`, any number for `multi`. Empty when the user only used `other`.',
    ),
  other: z.string().optional().describe('Free text from the "Something else" card.'),
  text: z.string().optional().describe('Free-form answer for `text` inputs.'),
  note: z
    .string()
    .optional()
    .describe(
      'Optional nuance the user attached to this decision. Quote it in the spec rather than paraphrasing it away.',
    ),
}).meta({ id: 'answer' })

export const QuestionSchema = z.strictObject({
  id: z.string().min(1),
  decision_id: z
    .string()
    .nullable()
    .optional()
    .describe('Decision the question is about, or `null` for a general question.'),
  body: z.string().min(1),
}).meta({ id: 'question' })

export const InterviewAnswersSchema = z
  .strictObject({
    schema_version: z.literal(1),
    round: z.int().min(1).describe('Round number this answers. Matches `rounds/round-NN.json`.'),
    interview: z.string().optional().describe('`interview.slug` echoed from the round.'),
    submitted_at: z
      .iso
      .datetime()
      .optional()
      .describe('ISO 8601 timestamp set by the server on write.'),
    answers: z
      .array(AnswerSchema)
      .describe('One entry per decision in the round, in round order.'),
    questions: z
      .array(QuestionSchema)
      .optional()
      .describe(
        "Questions the user asked the agent while answering. Reply to every one in the next round's `replies[]` (quote the question, answer in Markdown), and re-ask the decision if the answer could change it.",
      ),
    general_note: z
      .string()
      .optional()
      .describe('Free text the user wants carried into the artefact, not tied to one decision.'),
  })
  .describe(
    "The user's answers to one `interview-round.v1` round, written by the `vinta-ai-maestro` interview server to `<interview-dir>/answers/round-NN.json` when the browser form is submitted. The agent reads it back, scans for gaps and open questions, and writes the next round (or drafts the artefact).",
  )

export type InterviewAnswers = z.infer<typeof InterviewAnswersSchema>
export type Answer = z.infer<typeof AnswerSchema>
export type Question = z.infer<typeof QuestionSchema>
